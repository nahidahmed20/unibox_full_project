<?php

namespace App\Http\Controllers\backend;

use App\Http\Controllers\Controller;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Response;
use Carbon\Carbon;

class BackupController extends Controller
{
    protected string $backupDir;

    public function __construct()
    {
        $this->backupDir = storage_path('app/backups');
    }

    /**
     * Display a listing of database backups.
     */
    public function index()
    {
        if (!File::exists($this->backupDir)) {
            File::makeDirectory($this->backupDir, 0755, true);
        }

        $files = File::files($this->backupDir);
        $backups = [];
        $totalSize = 0;

        foreach ($files as $file) {
            $ext = strtolower($file->getExtension());
            if (in_array($ext, ['sql', 'gz', 'zip'])) {
                $size = $file->getSize();
                $totalSize += $size;
                $mtime = $file->getMTime();
                $backups[] = [
                    'name' => $file->getFilename(),
                    'path' => $file->getPathname(),
                    'size' => $this->formatBytes($size),
                    'size_bytes' => $size,
                    'created_at' => Carbon::createFromTimestamp($mtime),
                    'date_formatted' => Carbon::createFromTimestamp($mtime)->format('d M, Y h:i A'),
                    'age' => Carbon::createFromTimestamp($mtime)->diffForHumans(),
                ];
            }
        }

        // Sort descending by creation date
        usort($backups, function ($a, $b) {
            return $b['created_at']->timestamp <=> $a['created_at']->timestamp;
        });

        $dbName = config('database.connections.mysql.database');
        $latestBackup = count($backups) > 0 ? $backups[0]['date_formatted'] : 'No backups yet';

        return view('backend.backup.index', [
            'backups' => $backups,
            'totalBackups' => count($backups),
            'totalSize' => $this->formatBytes($totalSize),
            'latestBackup' => $latestBackup,
            'dbName' => $dbName,
        ]);
    }

    /**
     * Create a complete SQL backup of the MySQL database.
     */
    public function create()
    {
        try {
            if (!File::exists($this->backupDir)) {
                File::makeDirectory($this->backupDir, 0755, true);
            }

            $dbName = config('database.connections.mysql.database');
            $filename = 'backup_' . $dbName . '_' . date('Y-m-d_H-i-s') . '.sql';
            $filePath = $this->backupDir . DIRECTORY_SEPARATOR . $filename;

            $handle = fopen($filePath, 'w+');
            if (!$handle) {
                if (request()->ajax() || request()->wantsJson()) {
                    return response()->json(['success' => false, 'message' => 'Unable to write backup file to storage.'], 500);
                }
                return redirect()->route('backups.index')->with('error', 'Unable to write backup file to storage.');
            }

            // Write SQL Dump Header
            fwrite($handle, "-- =======================================================\n");
            fwrite($handle, "-- UNIBOX POS & E-COMMERCE DATABASE BACKUP\n");
            fwrite($handle, "-- Database: `{$dbName}`\n");
            fwrite($handle, "-- Timestamp: " . date('Y-m-d H:i:s') . "\n");
            fwrite($handle, "-- Generated by: " . (auth()->user()->name ?? 'System Admin') . "\n");
            fwrite($handle, "-- =======================================================\n\n");
            fwrite($handle, "SET FOREIGN_KEY_CHECKS=0;\n");
            fwrite($handle, "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n");
            fwrite($handle, "SET time_zone = \"+00:00\";\n\n");

            // Fetch all base tables
            $tables = DB::select('SHOW FULL TABLES WHERE Table_type = "BASE TABLE"');
            $dbKey = "Tables_in_" . $dbName;

            foreach ($tables as $tableObj) {
                $tableName = $tableObj->$dbKey ?? array_values((array)$tableObj)[0];

                // Table structure
                fwrite($handle, "\n-- --------------------------------------------------------\n");
                fwrite($handle, "-- Table structure for table `{$tableName}`\n");
                fwrite($handle, "-- --------------------------------------------------------\n");
                fwrite($handle, "DROP TABLE IF EXISTS `{$tableName}`;\n");

                $createTable = DB::select("SHOW CREATE TABLE `{$tableName}`");
                $createSql = $createTable[0]->{'Create Table'} ?? array_values((array)$createTable[0])[1];
                fwrite($handle, $createSql . ";\n\n");

                // Dump table records using cursor streaming (safe for tables without primary keys)
                $totalRows = DB::table($tableName)->count();
                if ($totalRows > 0) {
                    fwrite($handle, "-- Dumping data for table `{$tableName}` ({$totalRows} rows)\n");

                    $batchSize = 200;
                    $batchCount = 0;
                    $columns = [];
                    $valueRows = [];

                    foreach (DB::table($tableName)->cursor() as $row) {
                        if (empty($columns)) {
                            $columns = array_keys((array)$row);
                        }

                        $rowValues = [];
                        foreach ($columns as $col) {
                            $val = $row->$col;
                            if ($val === null) {
                                $rowValues[] = "NULL";
                            } else {
                                $valStr = str_replace(
                                    ["\\", "'", "\r", "\n", "\0"],
                                    ["\\\\", "\\'", "\\r", "\\n", "\\0"],
                                    (string)$val
                                );
                                $rowValues[] = "'" . $valStr . "'";
                            }
                        }
                        $valueRows[] = "(" . implode(', ', $rowValues) . ")";
                        $batchCount++;

                        if ($batchCount >= $batchSize) {
                            $colList = implode('`, `', $columns);
                            $insertSql = "INSERT INTO `{$tableName}` (`{$colList}`) VALUES \n" . implode(",\n", $valueRows) . ";\n";
                            fwrite($handle, $insertSql);
                            $valueRows = [];
                            $batchCount = 0;
                        }
                    }

                    if (!empty($valueRows)) {
                        $colList = implode('`, `', $columns);
                        $insertSql = "INSERT INTO `{$tableName}` (`{$colList}`) VALUES \n" . implode(",\n", $valueRows) . ";\n";
                        fwrite($handle, $insertSql);
                    }

                    fwrite($handle, "\n");
                }
            }

            fwrite($handle, "\nSET FOREIGN_KEY_CHECKS=1;\n");
            fwrite($handle, "-- Backup successfully completed at " . date('Y-m-d H:i:s') . "\n");
            fclose($handle);

            $fileSize = $this->formatBytes(File::size($filePath));

            if (request()->ajax() || request()->wantsJson()) {
                return response()->json([
                    'success' => true,
                    'message' => "Database backup created successfully! ({$filename} - {$fileSize})",
                    'filename' => $filename,
                    'size' => $fileSize,
                ]);
            }

            return redirect()->route('backups.index')->with('success', "Database backup created successfully! ({$filename})");
        } catch (\Throwable $e) {
            if (isset($handle) && is_resource($handle)) {
                fclose($handle);
            }
            if (request()->ajax() || request()->wantsJson()) {
                return response()->json([
                    'success' => false,
                    'message' => 'Backup failed: ' . $e->getMessage()
                ], 500);
            }
            return redirect()->route('backups.index')->with('error', 'Backup failed: ' . $e->getMessage());
        }
    }

    /**
     * Download a specific backup file.
     */
    public function download($file)
    {
        $cleanFile = basename($file);
        $filePath = $this->backupDir . DIRECTORY_SEPARATOR . $cleanFile;

        if (!File::exists($filePath)) {
            abort(404, 'Backup file not found.');
        }

        return Response::download($filePath, $cleanFile, [
            'Content-Type' => 'application/sql',
        ]);
    }

    /**
     * Delete a specific backup file.
     */
    public function destroy($file)
    {
        $cleanFile = basename($file);
        $filePath = $this->backupDir . DIRECTORY_SEPARATOR . $cleanFile;

        if (File::exists($filePath)) {
            File::delete($filePath);
            if (request()->ajax() || request()->wantsJson()) {
                return response()->json(['success' => true, 'message' => "Backup '{$cleanFile}' deleted successfully!"]);
            }
            return redirect()->route('backups.index')->with('success', "Backup '{$cleanFile}' deleted successfully!");
        }

        if (request()->ajax() || request()->wantsJson()) {
            return response()->json(['success' => false, 'message' => 'Backup file not found!'], 404);
        }
        return redirect()->route('backups.index')->with('error', 'Backup file not found!');
    }

    /**
     * Helper to format bytes into readable string.
     */
    private function formatBytes($bytes, $precision = 2)
    {
        $units = ['B', 'KB', 'MB', 'GB', 'TB'];
        $bytes = max($bytes, 0);
        $pow = floor(($bytes ? log($bytes) : 0) / log(1024));
        $pow = min($pow, count($units) - 1);
        $bytes /= pow(1024, $pow);
        return round($bytes, $precision) . ' ' . $units[$pow];
    }
}
